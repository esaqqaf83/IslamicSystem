-- Schema DDL for Islamic Finance Management System

-- Sequences
CREATE SEQUENCE SEQ_CUSTOMERS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ACCOUNTS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CONTRACTS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INSTALLMENTS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PAYMENTS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_AUDIT START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_GL_ENTRIES START WITH 1 INCREMENT BY 1 NOCACHE;

-- Core reference tables
CREATE TABLE TAB_CUSTOMERS (
  CUSTOMER_ID      NUMBER        PRIMARY KEY,
  CIF_NO           VARCHAR2(30)  UNIQUE NOT NULL,
  FULL_NAME        VARCHAR2(200) NOT NULL,
  NATIONAL_ID      VARCHAR2(30),
  MOBILE_NO        VARCHAR2(20),
  EMAIL_ADDR       VARCHAR2(120),
  STATUS           VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT       DATE          DEFAULT SYSDATE NOT NULL
);

CREATE TABLE TAB_ACCOUNTS (
  ACCOUNT_ID       NUMBER        PRIMARY KEY,
  CUSTOMER_ID      NUMBER        NOT NULL,
  ACCT_NO          VARCHAR2(34)  UNIQUE NOT NULL,
  CURRENCY_CODE    VARCHAR2(9)   NOT NULL,
  ACCT_TYPE        VARCHAR2(20)  NOT NULL,
  STATUS           VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  OPEN_DATE        DATE          DEFAULT SYSDATE NOT NULL,
  CLOSE_DATE       DATE,
  CONSTRAINT FK_ACCTS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
    REFERENCES TAB_CUSTOMERS(CUSTOMER_ID)
);

-- Product settings (abridged from provided model), PK/Unique added
CREATE TABLE TAB_PRDCTS_STTNGS (
  PRDCT_ID     NUMBER PRIMARY KEY,
  PRDCT_CODE   VARCHAR2(9 CHAR) NOT NULL,
  FIN_TYPE     VARCHAR2(11) NOT NULL,
  PROFIT_RATE  NUMBER,
  INSTALLMENT_OVERDUE_DAYS NUMBER,
  BASE_DAYS NUMBER(3) NOT NULL,
  MAIN_CUR_ID NUMBER NOT NULL,
  MAIN_CUR_CODE VARCHAR2(9) NOT NULL,
  ACCRUAL_FREQ NUMBER(3) DEFAULT 2 NOT NULL,
  RE_COMPUTATION_FLAG NUMBER(1) NOT NULL,
  PREPAY_REBATE_PRCNT NUMBER(3) DEFAULT 0 NOT NULL,
  GRACE_PERIOD NUMBER(3) DEFAULT 0 NOT NULL,
  GRACE_UNIT   VARCHAR2(9) DEFAULT 'MONTHS' NOT NULL,
  TENOR_UNITS  VARCHAR2(6) DEFAULT 'MONTHS' NOT NULL,
  DEFAULT_TENOR NUMBER(3) DEFAULT 12 NOT NULL,
  DEFAULT_FREQUENCY NUMBER(3) DEFAULT 1 NOT NULL,
  RENEWAL_MODE NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT UQ_PRDCTS_CODE UNIQUE (PRDCT_CODE)
);

-- Contracts
CREATE TABLE TAB_CONTRACTS (
  CONTRACT_ID        NUMBER        PRIMARY KEY,
  CONTRACT_NO        VARCHAR2(40)  UNIQUE NOT NULL,
  CUSTOMER_ID        NUMBER        NOT NULL,
  PRDCT_ID           NUMBER        NOT NULL,
  PRINCIPAL_AMT      NUMBER        NOT NULL,
  DISBURSED_AMT      NUMBER        DEFAULT 0 NOT NULL,
  CURRENCY_CODE      VARCHAR2(9)   NOT NULL,
  START_DATE         DATE          NOT NULL,
  MATURITY_DATE      DATE          NOT NULL,
  TENOR              NUMBER(5)     NOT NULL,
  TENOR_UNIT         VARCHAR2(6)   NOT NULL,
  FREQ               NUMBER(3)     NOT NULL,
  PROFIT_RATE        NUMBER        NOT NULL,
  FIN_PRODUCT_TYPE   VARCHAR2(20)  NOT NULL,
  FIN_TYPE           VARCHAR2(11)  NOT NULL,
  SETTLEMENT_ACCT_ID NUMBER        NOT NULL,
  STATUS             VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT         DATE          DEFAULT SYSDATE NOT NULL,
  UPDATED_AT         DATE,
  CONSTRAINT FK_CNTR_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES TAB_CUSTOMERS(CUSTOMER_ID),
  CONSTRAINT FK_CNTR_PRODUCT FOREIGN KEY (PRDCT_ID) REFERENCES TAB_PRDCTS_STTNGS(PRDCT_ID),
  CONSTRAINT FK_CNTR_SETTL_ACCT FOREIGN KEY (SETTLEMENT_ACCT_ID) REFERENCES TAB_ACCOUNTS(ACCOUNT_ID)
);

-- Installments
CREATE TABLE TAB_INSTALLMENTS (
  INSTALLMENT_ID     NUMBER        PRIMARY KEY,
  CONTRACT_ID        NUMBER        NOT NULL,
  INSTL_NO           NUMBER        NOT NULL,
  DUE_DATE           DATE          NOT NULL,
  PRINCIPAL_DUE      NUMBER        DEFAULT 0 NOT NULL,
  PROFIT_DUE         NUMBER        DEFAULT 0 NOT NULL,
  TAKAFUL_DUE        NUMBER        DEFAULT 0 NOT NULL,
  PENALTY_DUE        NUMBER        DEFAULT 0 NOT NULL,
  TOTAL_DUE          NUMBER        DEFAULT 0 NOT NULL,
  PRINCIPAL_PAID     NUMBER        DEFAULT 0 NOT NULL,
  PROFIT_PAID        NUMBER        DEFAULT 0 NOT NULL,
  TAKAFUL_PAID       NUMBER        DEFAULT 0 NOT NULL,
  PENALTY_PAID       NUMBER        DEFAULT 0 NOT NULL,
  STATUS             VARCHAR2(20)  DEFAULT 'DUE' NOT NULL,
  CREATED_AT         DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT FK_INSTL_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES TAB_CONTRACTS(CONTRACT_ID),
  CONSTRAINT UQ_INSTL_CNTR_NO UNIQUE (CONTRACT_ID, INSTL_NO)
);

-- Payments
CREATE TABLE TAB_PAYMENTS (
  PAYMENT_ID         NUMBER        PRIMARY KEY,
  CONTRACT_ID        NUMBER        NOT NULL,
  INSTALLMENT_ID     NUMBER,
  PAYMENT_DATE       DATE          DEFAULT SYSDATE NOT NULL,
  AMOUNT             NUMBER        NOT NULL,
  COMPONENT          VARCHAR2(20)  NOT NULL,
  SOURCE_ACCT_ID     NUMBER,
  REF_NO             VARCHAR2(60),
  NOTE               VARCHAR2(4000),
  CONSTRAINT FK_PYMT_CNTR FOREIGN KEY (CONTRACT_ID) REFERENCES TAB_CONTRACTS(CONTRACT_ID),
  CONSTRAINT FK_PYMT_INSTL FOREIGN KEY (INSTALLMENT_ID) REFERENCES TAB_INSTALLMENTS(INSTALLMENT_ID)
);

-- Audit
CREATE TABLE TAB_CONTRACT_AUDIT (
  AUDIT_ID           NUMBER        PRIMARY KEY,
  CONTRACT_ID        NUMBER        NOT NULL,
  EVENT_DATE         DATE          DEFAULT SYSDATE NOT NULL,
  EVENT_TYPE         VARCHAR2(40)  NOT NULL,
  EVENT_DESC         VARCHAR2(4000),
  OLD_VALUE          VARCHAR2(4000),
  NEW_VALUE          VARCHAR2(4000),
  USER_ID            VARCHAR2(60),
  CONSTRAINT FK_AUD_CNTR FOREIGN KEY (CONTRACT_ID) REFERENCES TAB_CONTRACTS(CONTRACT_ID)
);

-- Collaterals
CREATE TABLE TAB_COLLATERALS (
  COLLATERAL_ID      NUMBER        PRIMARY KEY,
  CONTRACT_ID        NUMBER        NOT NULL,
  TYPE_CODE          VARCHAR2(30)  NOT NULL,
  APPRAISED_VALUE    NUMBER        NOT NULL,
  DESCRIPTION        VARCHAR2(2000),
  CONSTRAINT FK_COL_CNTR FOREIGN KEY (CONTRACT_ID) REFERENCES TAB_CONTRACTS(CONTRACT_ID)
);

-- Guarantees
CREATE TABLE TAB_GUARANTEES (
  GUARANTEE_ID       NUMBER        PRIMARY KEY,
  CONTRACT_ID        NUMBER        NOT NULL,
  GUARANTOR_CUST_ID  NUMBER        NOT NULL,
  LIMIT_AMOUNT       NUMBER,
  STATUS             VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT FK_GUAR_CNTR FOREIGN KEY (CONTRACT_ID) REFERENCES TAB_CONTRACTS(CONTRACT_ID),
  CONSTRAINT FK_GUAR_CUST FOREIGN KEY (GUARANTOR_CUST_ID) REFERENCES TAB_CUSTOMERS(CUSTOMER_ID)
);

-- Campaigns
CREATE TABLE TAB_CAMPAIGNS (
  CAMPAIGN_ID        NUMBER        PRIMARY KEY,
  CAMPAIGN_CODE      VARCHAR2(30)  UNIQUE NOT NULL,
  NAME               VARCHAR2(200) NOT NULL,
  START_DATE         DATE          NOT NULL,
  END_DATE           DATE          NOT NULL,
  DISCOUNT_PCT       NUMBER        DEFAULT 0 NOT NULL
);

-- Penalty rules
CREATE TABLE TAB_PENALTY_RULES (
  RULE_ID            NUMBER        PRIMARY KEY,
  PRDCT_ID           NUMBER        NOT NULL,
  DAILY_RATE_PCT     NUMBER        NOT NULL,
  CAP_AT_PCT_OF_INST NUMBER        DEFAULT 100 NOT NULL,
  GRACE_DAYS         NUMBER        DEFAULT 0 NOT NULL,
  CONSTRAINT FK_PRULE_PRDCT FOREIGN KEY (PRDCT_ID) REFERENCES TAB_PRDCTS_STTNGS(PRDCT_ID)
);

-- Penalties ledger
CREATE TABLE TAB_PENALTIES (
  PENALTY_ID         NUMBER        PRIMARY KEY,
  INSTALLMENT_ID     NUMBER        NOT NULL,
  CALC_DATE          DATE          NOT NULL,
  AMOUNT             NUMBER        NOT NULL,
  POSTED_FLAG        NUMBER(1)     DEFAULT 0 NOT NULL,
  CONSTRAINT FK_PEN_INSTL FOREIGN KEY (INSTALLMENT_ID) REFERENCES TAB_INSTALLMENTS(INSTALLMENT_ID)
);

-- GL Entries
CREATE TABLE TAB_GL_ENTRIES (
  GL_ENTRY_ID        NUMBER        PRIMARY KEY,
  EVENT_DATE         DATE          DEFAULT SYSDATE NOT NULL,
  CONTRACT_ID        NUMBER,
  INSTALLMENT_ID     NUMBER,
  DR_ACCT            VARCHAR2(101) NOT NULL,
  CR_ACCT            VARCHAR2(101) NOT NULL,
  AMOUNT             NUMBER        NOT NULL,
  CURRENCY_CODE      VARCHAR2(9)   NOT NULL,
  NARRATION          VARCHAR2(4000),
  EVENT_TYPE         VARCHAR2(40)  NOT NULL,
  REF_NO             VARCHAR2(60),
  CONSTRAINT FK_GL_CNTR FOREIGN KEY (CONTRACT_ID) REFERENCES TAB_CONTRACTS(CONTRACT_ID),
  CONSTRAINT FK_GL_INSTL FOREIGN KEY (INSTALLMENT_ID) REFERENCES TAB_INSTALLMENTS(INSTALLMENT_ID)
);

-- Indexes
CREATE INDEX IDX_INSTL_CNTR_STATUS ON TAB_INSTALLMENTS(CONTRACT_ID, STATUS);
CREATE INDEX IDX_INSTL_DUE_DATE ON TAB_INSTALLMENTS(DUE_DATE);
CREATE INDEX IDX_PYMT_CNTR_DATE ON TAB_PAYMENTS(CONTRACT_ID, PAYMENT_DATE);

